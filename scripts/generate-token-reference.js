#!/usr/bin/env node

/**
 * AURAL UI - Token Reference Generator
 *
 * Regenerates specs/tokens/token-reference.md from the actual token CSS
 * files (tokens/core/**\/*.css, tokens/semantic/**\/*.css). This is the
 * project's "sync routine": instead of hand-maintaining a doc that drifts
 * from the source of truth, re-run this after any token change.
 *
 * Usage: node scripts/generate-token-reference.js
 */

const fs = require('fs');
const path = require('path');
const { buildTokenMap, ROOT } = require('./lib/token-map');

const OUT_FILE = path.join(ROOT, 'specs/tokens/token-reference.md');

function categoryOf(name) {
  if (/^--(neutral|primary|secondary|success|warning|error|info|purple|pink|amber)-/.test(name))
    return 'Color (core palette)';
  if (/^--color-/.test(name)) return 'Color (semantic)';
  if (/^--space-/.test(name)) return 'Spacing';
  if (/^--size-/.test(name)) return 'Size';
  if (/^--radius-/.test(name)) return 'Radius';
  if (/^--(shadow|glow)-/.test(name)) return 'Shadow / Elevation';
  if (/^--z-/.test(name)) return 'Z-Index';
  if (/^--(duration|ease|transition)-/.test(name)) return 'Motion';
  if (/^--(text|leading|tracking)-/.test(name)) return 'Typography';
  if (/^--font-/.test(name)) return 'Typography';
  return 'Other';
}

function main() {
  const { resolved } = buildTokenMap();
  const byCategory = new Map();
  for (const [name, info] of Object.entries(resolved)) {
    const cat = categoryOf(name);
    if (!byCategory.has(cat)) byCategory.set(cat, []);
    byCategory.get(cat).push({ name, ...info });
  }

  const order = [
    'Color (core palette)',
    'Color (semantic)',
    'Spacing',
    'Size',
    'Radius',
    'Shadow / Elevation',
    'Z-Index',
    'Typography',
    'Motion',
    'Other',
  ];

  let md = '# Token Reference\n\n';
  md += '> Generated by `npm run generate:token-docs` from `tokens/core/**/*.css` and ';
  md +=
    '`tokens/semantic/**/*.css`. Do not hand-edit this file — edit the token CSS and regenerate.\n\n';
  md += `Generated: ${new Date().toISOString().slice(0, 10)}\n\n`;

  for (const cat of order) {
    const tokens = byCategory.get(cat);
    if (!tokens || tokens.length === 0) continue;
    tokens.sort((a, b) => a.name.localeCompare(b.name));
    md += `## ${cat}\n\n`;
    md += '| Token | Value | Defined in |\n';
    md += '|---|---|---|\n';
    for (const t of tokens) {
      const value = t.value.length > 60 ? `${t.value.slice(0, 57)}...` : t.value;
      md += `| \`${t.name}\` | \`${value}\` | \`${t.file}\` |\n`;
    }
    md += '\n';
  }

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, md);
  console.log(`✓ Wrote ${path.relative(ROOT, OUT_FILE)} (${Object.keys(resolved).length} tokens)`);
}

main();
